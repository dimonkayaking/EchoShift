    public static void Draw(SpriteBatch spriteBatch, string text, Vector2 pos, Color color, int scale = 2)
    {
        if (string.IsNullOrEmpty(text)) return;
        int x = (int)pos.X;
        int y = (int)pos.Y;

        foreach (char rawCh in text)
        {
            char ch = rawCh;
            if (!Glyphs.TryGetValue(ch, out var g))
            {
                char upper = char.ToUpperInvariant(ch);
                if (!Glyphs.TryGetValue(upper, out g))
                    g = Glyphs[' '];
            }

            for (int row = 0; row < 7; row++)
            {
                string line = g[row];
                for (int col = 0; col < 5; col++)
                {
                    if (line[col] == '1')
                    {
                        spriteBatch.Draw(TextureManager.Pixel,
                            new Rectangle(x + col * scale, y + row * scale, scale, scale),
                            color);
                    }
                }
            }

            x += (5 + 1) * scale; // glyph + spacing
        }
    }

    public static Vector2 Measure(string text, int scale = 2)
    {
        if (string.IsNullOrEmpty(text)) return Vector2.Zero;
        int w = text.Length * (5 + 1) * scale;
        int h = 7 * scale;
        return new Vector2(w, h);
    }
